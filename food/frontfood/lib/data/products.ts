// Groupes d'options réutilisés tels quels sur plusieurs produits (mêmes
// libellés, ids préfixés par produit pour rester uniques dans le state du panier).
function sizeGroup(prefix: string, priceDeltas: [number, number, number] = [0, 150, 300]): ProductOptionGroup {
  return {
    id: `${prefix}-taille`,
    name: "Taille",
    type: "single",
    required: true,
    minSelect: 1,
    maxSelect: 1,
    options: [
      { id: `${prefix}-taille-s`, name: "Petit", priceDeltaCents: priceDeltas[0], isDefault: true },
      { id: `${prefix}-taille-m`, name: "Moyen", priceDeltaCents: priceDeltas[1] },
      { id: `${prefix}-taille-l`, name: "Grand", priceDeltaCents: priceDeltas[2] },
    ],
  };
}

function cuissonGroup(prefix: string): ProductOptionGroup {
  return {
    id: `${prefix}-cuisson`,
    name: "Cuisson",
    type: "single",
    required: true,
    minSelect: 1,
    maxSelect: 1,
    options: [
      { id: `${prefix}-cuisson-saignant`, name: "Saignant", priceDeltaCents: 0 },
      { id: `${prefix}-cuisson-point`, name: "À point", priceDeltaCents: 0, isDefault: true },
      { id: `${prefix}-cuisson-bien-cuit`, name: "Bien cuit", priceDeltaCents: 0 },
    ],
  };
}

function sauceGroup(prefix: string, sauces = ["Mayonnaise", "Ketchup", "Algérienne", "BBQ"]): ProductOptionGroup {
  return {
    id: `${prefix}-sauce`,
    name: "Sauce",
    type: "single",
    required: false,
    minSelect: 0,
    maxSelect: 1,
    options: sauces.map((s, i) => ({
      id: `${prefix}-sauce-${i}`,
      name: s,
      priceDeltaCents: 0,
      isDefault: i === 0,
    })),
  };
}

function supplementsGroup(prefix: string): ProductOptionGroup {
  return {
    id: `${prefix}-supplements`,
    name: "Suppléments",
    type: "multiple",
    required: false,
    minSelect: 0,
    maxSelect: 4,
    options: [
      { id: `${prefix}-supp-fromage`, name: "Fromage", priceDeltaCents: 100 },
      { id: `${prefix}-supp-bacon`, name: "Bacon", priceDeltaCents: 200 },
      { id: `${prefix}-supp-oeuf`, name: "Œuf", priceDeltaCents: 150 },
      { id: `${prefix}-supp-avocat`, name: "Avocat", priceDeltaCents: 200 },
    ],
  };
}

function retirerGroup(prefix: string, items = ["Sans oignon", "Sans tomate", "Sans salade"]): ProductOptionGroup {
  return {
    id: `${prefix}-retirer`,
    name: "Retirer",
    type: "multiple",
    required: false,
    minSelect: 0,
    maxSelect: items.length,
    options: items.map((it, i) => ({ id: `${prefix}-retirer-${i}`, name: it, priceDeltaCents: 0 })),
  };
}

